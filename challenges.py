def get_challenge_for_date(d: date) -> dict:
    """چالش قطعی برای یک تاریخ مشخص — همه در یک روز چالش یکسان می‌گیرند."""
    index = d.toordinal() % len(CHALLENGES)
    return CHALLENGES[index]


def get_today_challenge() -> dict:
    return get_challenge_for_date(date.today())
